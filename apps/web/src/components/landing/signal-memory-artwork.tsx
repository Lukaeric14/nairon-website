type SignalMemoryArtworkProps = {
	className?: string;
	tone?: "blue" | "green";
	compact?: boolean;
};

export function SignalMemoryArtwork({
	className,
	tone = "blue",
	compact = false,
}: SignalMemoryArtworkProps) {
	const toneClass =
		tone === "green" ? "text-[#63BF6A]" : "text-[#5E8BFF]";

	return (
		<div
			aria-hidden="true"
			className={cn(
				"relative overflow-hidden rounded-[8px] border border-[#171612]/10 bg-[#FDFCF8]",
				className,
			)}
		>
			<div
				className={cn(
					"absolute inset-x-0 flex justify-center",
					compact ? "top-6" : "top-8",
				)}
			>
				<pre
					className={cn(
						"select-none whitespace-pre font-mono leading-[0.72]",
						toneClass,
						compact
							? "text-[5.2px] sm:text-[6px] md:text-[6.8px]"
							: "text-[5.8px] sm:text-[6.8px] md:text-[7.6px]",
					)}
				>
					{asciiMemoryForm}
				</pre>
			</div>
		</div>
	);
}
